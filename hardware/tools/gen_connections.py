"""Per-block connection tables for gate reviews (owner request at GATE V2:
the generated label-only schematic is slow to review - "how are the parts
connected" should be readable as a table).

From the SKiDL circuit (same source as the netlist and gen_sch):
  per block   parts (ref, part, value/MPN, LCSC, DNP)
              every connected pin: pin, datasheet pin name, net, and what else
              sits on that net (same block: ref.pin; other blocks: tagged)
  net index   every net with all its members and the blocks it spans
Power/ground nets are summarized (member count) in the pin tables; the net
index lists them in full.
  uv run python tools/gen_connections.py   ->  docs/review/<REV_TAG>_connections.md
"""
import builtins
import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
ROOT = HERE.parent
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(HERE / "tools"))

from block_refs import BLOCK_REFS, ORDER, TITLES, block_of  # noqa: E402
from revision import GATE, REV_LABEL, REV_TAG  # noqa: E402

OUT = ROOT / "docs" / "review" / f"{REV_TAG}_connections.md"
POWER = {"GND", "+3V3", "+3V3_M2", "+3V3_EFUSE"}
SHORT = {"m2_keyb_edge": "edge", "power_3v3": "power", "usb_esd": "usb",
         "sideband_recovery": "recovery", "esp32s3_companion": "MCU", "leds": "leds",
         "io_header": "io", "edge_expansion": "exp", "host_sideband": "sideband"}


def refkey(r):
    m = re.match(r"([A-Z]+)(\d+)", r)
    return (m.group(1), int(m.group(2)))


def pinkey(n):
    return (0, int(n)) if str(n).isdigit() else (1, str(n))


def main():
    import design
    design.build()
    circuit = builtins.default_circuit
    rev = subprocess.run(["git", "describe", "--always", "--dirty"], cwd=ROOT,
                         capture_output=True, text=True).stdout.strip() or "dev"
    parts = {p.ref: p for p in circuit.parts}
    unknown = [r for r in parts if block_of(r) == "misc"]
    assert not unknown, f"parts not assigned to a block: {unknown}"

    members = {}                                   # net -> [(ref, num, name)]
    for p in parts.values():
        for pin in p.pins:
            if pin.nets:
                nm = "" if str(pin.name) == "~" else str(pin.name)   # passives
                members.setdefault(pin.nets[0].name, []).append((p.ref, str(pin.num), nm))
    for m in members.values():
        m.sort(key=lambda t: (refkey(t[0]), pinkey(t[1])))

    def other(net, ref, num, blk):
        if net in POWER:
            return f"*{len(members[net])} pins*"
        out = []
        for r, n, name in members[net]:
            if (r, n) == (ref, num):
                continue
            b = block_of(r)
            tag = "" if b == blk else f" ({SHORT[b]})"
            out.append(f"{r}.{n} {name}".rstrip() + tag)
        return ", ".join(out) if out else "—"

    L = []
    w = L.append
    w(f"# {REV_LABEL} — connections per block ({GATE} review)\n")
    w(f"Generated by `hardware/tools/gen_connections.py` from the SKiDL design at "
      f"`{rev}`; do not hand-edit. Same source as the netlist, the BOM and "
      f"`docs/review/{REV_TAG}_schematic.pdf`; `make check` verifies the v2 edge "
      f"contract pin by pin (`tools/check_v2_netlist.py`).\n")
    w("How to read: each block lists its parts, then every connected pin with "
      "the net and the other pins on that net. A tag in brackets is another "
      f"block ({', '.join(f'`{v}` = {k}' for k, v in SHORT.items())}). "
      f"Power nets ({', '.join(sorted(POWER))}) show only a member count; the "
      "net index at the end lists everything.\n")
    w("## Blocks\n")
    for blk in ORDER:
        w(f"- [{TITLES[blk]}](#{blk}) — {', '.join(sorted(BLOCK_REFS[blk], key=refkey))}")
    w("")
    for blk in ORDER:
        w(f'<a id="{blk}"></a>\n\n## {TITLES[blk]}  (`{blk}`)\n')
        refs = sorted(BLOCK_REFS[blk], key=refkey)
        w("| Ref | Part | Value | MPN | LCSC | DNP |\n|---|---|---|---|---|---|")
        for r in refs:
            p = parts[r]
            f = p.fields
            w(f"| {r} | {p.name} | {p.value} | {f.get('MPN', '')} | {f.get('LCSC', '')} | "
              f"{'DNP' if f.get('DNP') else ''} |")
        w("")
        w("| Pin | Pin name | Net | Also on this net |\n|---|---|---|---|")
        for r in refs:
            p = parts[r]
            for pin in sorted(p.pins, key=lambda q: pinkey(q.num)):
                if not pin.nets:
                    continue
                net = pin.nets[0].name
                nm = "" if str(pin.name) == "~" else pin.name
                w(f"| {r}.{pin.num} | {nm} | `{net}` | {other(net, r, str(pin.num), blk)} |")
        w("")
    w("## Net index\n")
    w("| Net | Blocks | Members (ref.pin name) |\n|---|---|---|")
    for net in sorted(members, key=lambda n: (n not in POWER, n)):
        blks = sorted({SHORT[block_of(r)] for r, _, _ in members[net]})
        w(f"| `{net}` | {', '.join(blks)} | "
          f"{', '.join(f'{r}.{n} {name}'.rstrip() for r, n, name in members[net])} |")
    w("")
    OUT.write_text("\n".join(L) + "\n")
    print("wrote", OUT, f"({len(parts)} parts, {len(members)} nets)")


if __name__ == "__main__":
    main()
