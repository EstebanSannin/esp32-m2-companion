from kicad_exit import run

HERE = Path(__file__).resolve().parent.parent
ROOT = HERE.parent
PCB = HERE / "kicad" / "esp32_m2_companion.kicad_pcb"
NET = HERE / "build" / "esp32_m2_companion.net"
from revision import GATE, REV_LABEL, REV_TAG  # noqa: E402
OUT = ROOT / "docs" / "review" / f"{REV_TAG}_label_inventory.md"

# where each net name comes from (CLAUDE.md naming rule)
NET_SOURCE = {
    "GND": "power", "+3V3": "power (card rail, after FB1)",
    "+3V3_M2": "power (M.2 3.3 V input, before FB1)",
    "USBH3_D_P": "Mallow X17 (M.2 pin 7)", "USBH3_D_N": "Mallow X17 (M.2 pin 9)",
    "PERST_n": "Mallow X17 PERST# (M.2 pin 50), # -> _n",
    "PCIE_1_GPIO_5": "Mallow X17 (M.2 pin 20)",
    "W_DISABLE1_n": "M.2 WWAN W_DISABLE1# (pin 8), # -> _n",
    "EN": "WROOM-1 pin name", "TXD0": "WROOM-1 pin name", "RXD0": "WROOM-1 pin name",
    "USB_D_N": "WROOM-1 pin name (IO19/USB_D-)", "USB_D_P": "WROOM-1 pin name (IO20/USB_D+)",
    "USB_D_N_ESD": "derived: USB_D_N between U1 and series R8",
    "USB_D_P_ESD": "derived: USB_D_P between U1 and series R7",
    "LED_STATUS_n": "functional (IO48, active-low LED cathode)",
    "LED_PWR_A": "functional (D3 anode / R3, rev B; was auto N$1)",
    "LED_STATUS_A": "functional (D4 anode / R4, rev B; was auto N$2)",
}
FLAGS = {}   # rev-B naming deviations all resolved at GATE B2 (L1, L2)
SILK_MARK = {
    "D3": "silk bar = cathode (pad 1) — NEW in rev B (v1 had none)",
    "D4": "silk bar = cathode (pad 1) — NEW in rev B (v1 had none)",
    "D1": "SOT-23 silk triangle at pin 1", "D2": "SOT-23 silk triangle at pin 1",
    "U1": "SOT-23-6 silk triangle at pin 1", "U2": "module silk triangle at pin 1",
    "J3": "JST silk arrow at pin 1", "J4": "JST silk arrow at pin 1",
    # v2.0 Rev A
    "U3": "UQFN-16 silk dot at pin 1 (corner)", "U4": "UQFN-16 silk dot at pin 1 (corner)",
    "U5": "UQFN-16 silk dot at pin 1 (corner)", "U6": "VQFN-10 silk dot at pin 1 (corner)",
    "Q1": "SOT-563 silk triangle at pin 1", "Q2": "SOT-563 silk triangle at pin 1",
    "Q3": "SOT-563 silk triangle at pin 1",
}


def parse_netlist():
    src = NET.read_text()
    comps = {}
    for c in re.split(r"\(comp\s*\n", src)[1:]:
        ref = re.search(r'\(ref "([^"]+)"\)', c).group(1)
        f = dict(re.findall(r'\(name "([^"]+)"\)\s*"([^"]*)"', c))
        comps[ref] = {"value": re.search(r'\(value "([^"]*)"\)', c).group(1),
                      "fp": re.search(r'\(footprint "([^"]*)"\)', c).group(1),
                      **f}
    nets = {}
    for n in re.split(r"\(net\s*\n", src)[1:]:
        m = re.search(r'\(name "([^"]*)"\)', n)
        if not m:
            continue
        nodes = re.findall(r'\(ref "([^"]+)"\)\s*\(pin "([^"]+)"\)', n)
        nets[m.group(1)] = [f"{r}.{p}" for r, p in nodes]
    return comps, nets


def mm(v):
    return v / 1e6


def main():
    comps, nets = parse_netlist()
    b = pcbnew.LoadBoard(str(PCB))
    from gitrev import gitrev
    rev = gitrev()
    pol = json.loads((HERE / "build" / "fab" / "polarity.json").read_text()) \
        if (HERE / "build" / "fab" / "polarity.json").exists() else {"parts": []}
    polrow = {p["ref"]: p for p in pol["parts"]}
    fps = {fp.GetReference(): fp for fp in b.GetFootprints()}
    L = []
    w = L.append
    w(f"# {REV_LABEL} label inventory — for owner review ({GATE})\n")
    w(f"Generated by `hardware/tools/label_inventory.py` from the netlist and "
      f"board at `{rev}`. Re-run after any change; do not hand-edit.\n")
    w(f"Review artifacts: `docs/review/{REV_TAG}_schematic.pdf`, "
      f"`docs/review/{REV_TAG}_drawings.pdf` (assembly + fab), "
      f"`docs/review/{REV_TAG}_connections.md` (per-block connection tables), "
      "`fab/polarity_checklist.md` (after `make fab`).\n")
    if REV_TAG != "rev_b":
        w("## GATE V3 silkscreen (owner, 2026-10-10)\n")
        w("| # | Label | Decision |\n|---|---|---|")
        w("| V1 | Top | board name split around the mounting notch: `ESP32-M2` / `COMPANION` (0.9 mm) |")
        w("| V2 | Back | logo + `v2.0 Rev A 2026-10` / `Designed in Italy` / `samnium.tech` (0.8 mm) |")
        w("| V3 | Test points | TP3–TP6 removed in v2; `EN` / `BOOT` legends beside TP1 / TP2 |")
        w("| V4 | Refdes | all 0.8 mm (DRC min); hidden refs: `Silk refdes` column of section 1 |")
        w("")
        w("<details><summary>Rev B decisions (GATE B2, kept for history)</summary>\n")
    w("## GATE B2 decisions (owner, 2026-10-06)\n")
    w("| # | Label | Decision |\n|---|---|---|")
    w("| L1 | Nets `N$1`, `N$2` | renamed → `LED_PWR_A`, `LED_STATUS_A` |")
    w("| L2 | Net `IO0_BOOT` | renamed → `IO0` (WROOM-1 pin name, CLAUDE.md rule) |")
    w("| L3 | J3/J4 silk | legends `J3 QWIIC` / `J4 UART/SPI` + pin-1 arrows; per-pin pinout in DATASHEET |")
    w("| L4 | TP1–TP6 silk | function names `EN BOOT TX RX 3V3 GND`; `TPn` on fab layer |")
    w("| L5 | Board text | `v1.0 Rev B` — fixes only; major number reserved for feature additions |")
    w("| L6 | Fab-only refdes | R2, U2 (no legal silk spot) |")
    w("| L7 | Silk text size | 0.8 mm / 0.153 mm (JLC minimum = board rule) |")
    w("| L8 | Unit serial | ESP32-S3 base MAC = module Data Matrix; no PCB serial (confirm at bring-up) |")
    w("")
    if REV_TAG != "rev_b":
        w("</details>\n")

    # 1. refdes & values
    w("## 1. Reference designators and values\n")
    w("| Ref | Value (BOM Comment) | MPN | LCSC | JLC | Side | Silk refdes | Notes |")
    w("|---|---|---|---|---|---|---|---|")
    for ref in sorted(comps, key=lambda r: (re.sub(r"\d", "", r), int(re.sub(r"\D", "", r) or 0))):
        c = comps[ref]
        fp = fps.get(ref)
        side = ("bottom" if fp.IsFlipped() else "top") if fp else "—"
        r = fp.Reference() if fp else None
        if ref == "J1":
            silk = "none (edge fingers)"
        elif r is None or not r.IsVisible():
            silk = "hidden"
        elif r.GetLayer() in (pcbnew.F_SilkS, pcbnew.B_SilkS):
            silk = "silk"
        else:
            silk = "**fab only**" + (" (silk legend replaces it)" if ref in ("J3", "J4")
                                     else " (silk: function label)" if ref.startswith("TP")
                                     else "")
        notes = []
        if c.get("DNP"):
            notes.append("**DNP**")
        if ref in SILK_MARK:
            notes.append("polarized")
        if ref.startswith("TP"):
            notes.append("bare pad, not placed")
        if c["value"] in ("SI-tune", "Conn_01x04", "Conn_01x08", "green", "red"):
            notes.append(f"value `{c['value']}` is generic — check BOM Comment")
        w(f"| {ref} | {c['value']} | {c.get('MPN', '')} | {c.get('LCSC', '')} | "
          f"{c.get('JLC', '')} | {side} | {silk} | {'; '.join(notes)} |")
    w("")

    # 2. nets
    w("## 2. Net names\n")
    w("Rule (CLAUDE.md): names verbatim from the source datasheets; datasheet "
      "`#` → `_n`. M.2 edge nets use Mallow X17 names where they exist.\n")
    w("| Net | Name source | Members | Check |\n|---|---|---|---|")
    for n in sorted(nets):
        members = nets[n]
        src = NET_SOURCE.get(n) or ("WROOM-1 pin name" if re.fullmatch(r"IO\d+", n) else "?")
        chk = FLAGS.get(n, "OK" if src != "?" else "**no source recorded**")
        if "#" in n:
            chk = "**contains '#'**"
        mem = ", ".join(members[:8]) + (f" … (+{len(members)-8})" if len(members) > 8 else "")
        w(f"| `{n}` | {src} | {mem} | {chk} |")
    w("")

    # 3. silkscreen text
    w("## 3. Silkscreen text (every item)\n")
    w("Positions in board mm (KiCad coords, card top edge y = 108, fingers y = 150).\n")
    w("| Side | Text | Kind | x, y | Height |\n|---|---|---|---|---|")
    rows = []
    for fp in b.GetFootprints():
        for f in fp.GetFields():
            if f.GetLayer() in (pcbnew.F_SilkS, pcbnew.B_SilkS) and f.IsVisible():
                rows.append((f.GetLayer(), f.GetShownText(False), f"{f.GetName()} of {fp.GetReference()}",
                             f.GetPosition(), f.GetTextHeight()))
    for d in b.GetDrawings():
        if d.GetLayer() in (pcbnew.F_SilkS, pcbnew.B_SilkS) and d.GetClass() == "PCB_TEXT":
            g = d.GetParentGroup()
            rows.append((d.GetLayer(), d.GetShownText(False),
                         f"board text ({g.GetName() if g else 'ungrouped'})",
                         d.GetPosition(), d.GetTextHeight()))
    for layer, t, kind, p, h in sorted(rows, key=lambda r: (r[0], r[2].startswith("Ref"), r[1])):
        w(f"| {'top' if layer == pcbnew.F_SilkS else 'bottom'} | `{t}` | {kind} | "
          f"{mm(p.x):.2f}, {mm(p.y):.2f} | {mm(h):.2f} |")
    w("\nNon-text silk: logo (bottom, 659 rects, group `silk_label`); component "
      "outlines from the KiCad library footprints.\n")

    # 4. polarity
    w("## 4. Polarity and pin-1 markers\n")
    cpl = {}
    cplf = HERE / "build" / "fab" / "esp32_m2_companion_cpl_jlc.csv"
    if cplf.exists():
        cpl = {r["Designator"]: r for r in csv.DictReader(open(cplf))}
    w("| Ref | Silk marker | Must see in JLC preview | KiCad rot | CPL rot |\n|---|---|---|---|---|")
    for ref in [r for r in SILK_MARK if r in fps]:
        fp = fps[ref]
        p = polrow.get(ref, {})
        crot = f"{float(cpl[ref]['Rotation']):.0f}°" if ref in cpl else "(run make fab)"
        w(f"| {ref} | {SILK_MARK[ref]} | {p.get('check', '(run make fab)')} | "
          f"{fp.GetOrientationDegrees():.0f}° {'bottom' if fp.IsFlipped() else 'top'} | "
          f"{crot} |")
    w("\nLED anode = pad 2 = the pad sharing a net with the series resistor "
      "(asserted by `tools/polarity_report.py`, negative-tested).\n")

    # 5. connectors
    w("## 5. Connector pinouts\n")
    pin_net = {}
    for n, members in nets.items():
        for m in members:
            pin_net[m] = n
    for ref, title in (("J3", "J3 — Qwiic (JST SH-4); silk legend `J3 QWIIC`"),
                       ("J4", "J4 — UART/SPI/GPIO (JST SH-8); silk legend `J4 UART/SPI`")):
        w(f"### {title}\n\n| Pin | Net | 2-char alt. label |\n|---|---|---|")
        alt = {"J3": ["GND", "3V3", "SDA", "SCL"],
               "J4": ["TX", "RX", "CS", "MO", "CK", "MI", "14", "21"]}[ref]
        for i in range(1, len(alt) + 1):
            w(f"| {i} | `{pin_net.get(f'{ref}.{i}', 'NC')}` | {alt[i-1]} |")
        w("")
    w("Qwiic standard order is GND, 3V3, SDA, SCL — J3 matches.\n")
    w("### J1 — M.2 edge, pins with a non-power net\n\n| Pin | Net |\n|---|---|")
    for m, n in sorted(pin_net.items(), key=lambda kv: int(kv[0].split(".")[1]) if kv[0].startswith("J1.") and kv[0].split(".")[1].isdigit() else 999):
        if m.startswith("J1.") and n not in ("GND", "+3V3_M2"):
            w(f"| {m.split('.')[1]} | `{n}` |")
    w("")

    # 6. test points
    w("## 6. Test points\n\n| Ref | Net | Silk label | x, y (bottom) |\n|---|---|---|---|")
    silk_by_pos = [(r[1], r[3]) for r in rows if r[2].startswith("board text")]
    for ref in sorted(r for r in fps if re.fullmatch(r"TP\d+", r)):
        fp = fps[ref]
        pad = list(fp.Pads())[0]
        q = pad.GetPosition()
        near = min(silk_by_pos, key=lambda tp: (tp[1].x - q.x) ** 2 + (tp[1].y - q.y) ** 2)
        w(f"| {ref} | `{pad.GetNetname()}` | `{near[0]}` | {mm(q.x):.1f}, {mm(q.y):.1f} |")
    w("")

    # 7. fab/assembly notes
    w("## 7. Fab and assembly notes\n")
    w("- `fab/README.md` — order settings (rev B; the v2 6-layer settings land at GATE V4).")
    w(f"- `docs/review/{REV_TAG}_drawings.pdf` sheet 1 notes (assembly) and sheet 2 "
      "notes (fab) — please review the wording.")
    w("- `DATASHEET.md` — regenerated: pin 8 restored, routed notch, no bevel, "
      "silk markings for LEDs/TPs.")
    OUT.write_text("\n".join(L) + "\n")
    print("wrote", OUT)


if __name__ == "__main__":
    run(main)
