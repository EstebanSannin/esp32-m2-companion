"""Complete label inventory for the owner's label review (GATE B2).

Run with KiCad's python:  .../python3 tools/label_inventory.py
Writes docs/review/<REV_TAG>_label_inventory.md (tools/revision.py),
generated from the netlist
(refs, values, LCSC, nets) and the board (silkscreen, markers, positions),
so it is complete by construction and re-runnable after any change.
Naming checks follow CLAUDE.md: net names verbatim from datasheets,
datasheet '#' -> '_n'.
"""

import csv
