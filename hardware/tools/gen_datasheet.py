def _connector_table(part, fn_map):
    rows = []
    for pin in sorted(part.pins, key=lambda p: int(p.num)):
        net = pin.nets[0].name if pin.nets else "—"
        sig = net
        rows.append(f"| {pin.num} | {sig} | {fn_map.get(net, '')} |")
    return "\n".join(rows)


def _edge_table(j1):
    rows = []
    for pin in sorted(j1.pins, key=lambda p: int(p.num)):
        if not pin.nets:
            continue
        net = pin.nets[0].name
        base = net.replace("+3V3_M2", "VCC_3V3")
        fn = EDGE_FN.get(pin.name, "") or NET_FN.get(net, "")
        if not fn and net == "GND" and pin.name.startswith("CONFIG_"):
            fn = "Grounded: CONFIG state 6 (ADR 0006)"
        rows.append(f"| {pin.num} | {pin.name} | {net} | {fn} |")
    return "\n".join(rows)


def main():
    import design
    design.build()
    import builtins
    circuit = builtins.default_circuit
    parts = {p.ref: p for p in circuit.parts}

    git_rev = subprocess.run(["git", "describe", "--always", "--dirty"],
                             cwd=ROOT, capture_output=True,
                             text=True).stdout.strip() or "dev"

    top_legend = "\n".join(f"| {i} | {t} |" for i, (_r, t)
                            in enumerate(TOP_CALLOUTS, 1))
    bot_legend = "\n".join(f"| {i} | {t} |" for i, (_r, t)
                            in enumerate(BOT_CALLOUTS, 1))
    md = TEMPLATE.format(
        date=date.today().isoformat(), rev=git_rev,
        j3=_connector_table(parts["J3"], J3_FN),
        j4=_connector_table(parts["J4"], J4_FN),
        edge=_edge_table(parts["J1"]),
        top_legend=top_legend, bot_legend=bot_legend,
    )
    out = ROOT / "DATASHEET.md"
    out.write_text(md)
    print("wrote", out)


